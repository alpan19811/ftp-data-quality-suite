-- ============================================================
-- 01_create_schemas.sql
-- Создание схем базы данных (слоёв данных)
-- ============================================================
-- Архитектура повторяет классический банковский DWH-подход:
--   source -> dwh -> mart
-- ============================================================

-- source: сырые данные, как они приходят из операционных систем банка
-- (АБС, кредитный конвейер, казначейство). Данные без трансформаций.
CREATE SCHEMA IF NOT EXISTS source;

-- dwh: корпоративное хранилище данных.
-- Очищенные и стандартизированные справочники (измерения) и факты.
CREATE SCHEMA IF NOT EXISTS dwh;

-- mart: витрины данных. Финальный слой для аналитики, отчётности
-- и расчёта трансфертных ставок (предметная область вакансии).
CREATE SCHEMA IF NOT EXISTS mart;

-- dq: служебная схема для хранения результатов проверок качества данных
-- (используем на этапе развития проекта).
CREATE SCHEMA IF NOT EXISTS dq;