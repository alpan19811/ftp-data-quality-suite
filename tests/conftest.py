"""
conftest.py — pytest-фикстуры для всех тестов проекта.

Здесь мы создаём фикстуру db_conn, которая:
  - открывает соединение с PostgreSQL перед запуском тестов;
  - передаёт это соединение в каждый тест как параметр;
  - закрывает соединение после завершения всех тестов.
"""
import pytest

from src.db import get_connection


@pytest.fixture(scope="session")
def db_conn():
    """
    Фикстура с подключением к БД.

    scope="session" означает, что соединение создаётся ОДИН РАЗ
    на всю сессию запуска тестов (а не для каждого теста отдельно).
    Это экономит время и ресурсы.
    """
    conn = get_connection()
    yield conn
    conn.close()